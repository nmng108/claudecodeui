/**
 * Contract for managing the SSH key git uses to authenticate over SSH.
 *
 * The native implementation works on the key files of the current user. The
 * interface exists so another implementation can keep the private key out of
 * this process (for example in a separate container) without the routes or the
 * UI changing.
 */

export type SshKeyStatus = 'present' | 'missing' | 'unreadable';

export type SshKeyInfo = {
  /** `unreadable`: a private key exists but its public half cannot be read (for example it needs a passphrase). */
  status: SshKeyStatus;
  /** `generated` keys were created by this app and may be replaced from the UI; `existing` ones never are. */
  origin: 'generated' | 'existing' | null;
  /** Human-readable algorithm, for example `ED25519`. */
  type: string | null;
  /** One-line OpenSSH public key, the value to add to a git server. Never the private key. */
  publicKey: string | null;
  /** `SHA256:...` fingerprint of the public key, as git servers display it. */
  fingerprint: string | null;
  comment: string | null;
  /** Where the key lives, for display (home directory abbreviated to `~`). */
  location: string | null;
  /** A key can be generated now: none exists and the directory is writable. */
  canGenerate: boolean;
  /** The key was generated by this app, so it can be replaced after a confirmation. */
  canReplace: boolean;
  /** Why the key is unreadable, or why one cannot be generated. */
  reason: 'passphrase-or-unreadable' | 'read-only' | 'ssh-keygen-missing' | null;
  /** Which implementation answered: the user's own key files (
ative) or the ssh-agent sidecar (gent). */
  provider: 'native' | 'agent';
};

export type GenerateSshKeyOptions = {
  /** Replace the existing key. Honoured only for a key this app generated. */
  replace?: boolean;
};

export interface SshKeyProvider {
  getKey(): Promise<SshKeyInfo>;
  generateKey(options?: GenerateSshKeyOptions): Promise<SshKeyInfo>;
}